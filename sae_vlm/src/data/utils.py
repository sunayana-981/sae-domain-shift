"""Higher-level data helpers.

Provides dataset loaders and pre-computed artifact readers used by
analysis scripts (kmeans.py, save_csv.py, src/demo/utils.py).
Replaces the deleted tasks/utils.py higher-level API.
"""

import json
import os
from pathlib import Path
from typing import Dict, List, Optional

import torch

from src.data.dataset_registry import get_dataset, get_classnames, load_registry

_CLASSNAMES_ROOT = Path(__file__).resolve().parents[2] / "configs" / "classnames"

_DEFAULT_DATASETS = [
    "eurosat", "caltech101", "medmnist", "dtd", "ucf101", "pets", "imagenet",
]


def load_datasets(
    names: Optional[List[str]] = None,
    include_imagenet: bool = False,
    max_samples: Optional[int] = None,
) -> Dict:
    """Load multiple datasets by name → {name: HF Dataset or None}.

    Parameters
    ----------
    names           : list of dataset names; defaults to the standard suite
    include_imagenet: if False (default), sets imagenet entry to None (large)
    max_samples     : optional per-dataset cap
    """
    registry = load_registry()
    names    = names or _DEFAULT_DATASETS

    datasets = {}
    for name in names:
        if name == "imagenet" and not include_imagenet:
            datasets[name] = None
            continue
        if name not in registry:
            datasets[name] = None
            continue
        try:
            datasets[name] = get_dataset(name, registry=registry, max_samples=max_samples)
        except Exception as e:
            print(f"  [WARN] Could not load dataset '{name}': {e}")
            datasets[name] = None
    return datasets


def get_all_classnames(
    datasets: Dict,
    data_root: Optional[str] = None,
) -> Dict[str, List[str]]:
    """Load classnames for each dataset in ``datasets``.

    Falls back to classname files in ``data_root`` if the dataset doesn't
    embed a ClassLabel feature.

    Returns {dataset_name: [str, ...]}
    """
    registry   = load_registry()
    classnames = {}

    for name, ds in datasets.items():
        if ds is None:
            classnames[name] = []
            continue
        try:
            classnames[name] = get_classnames(name, dataset=ds, registry=registry)
        except Exception as e:
            print(f"  [WARN] Could not get classnames for '{name}': {e}")
            classnames[name] = []

    return classnames


def get_max_acts_and_images(
    datasets: Dict,
    root: str = "out/feature_data",
    sae_runname: str = "sae_base",
    vit_name: str = "base",
):
    """Load pre-computed max-activating image indices and mean activations.

    Artifacts must have been generated by ``eval_sae.py --tasks feature_stats``
    and saved under ``{root}/{vit_name}/{dataset_name}/``.

    Returns
    -------
    max_act_imgs : {dataset_name: Tensor[N_FEAT, N_TOP] or None}
    mean_acts    : {dataset_name: Tensor[N_FEAT]        or None}
    """
    max_act_imgs: Dict = {}
    mean_acts:    Dict = {}

    for name in datasets:
        feat_dir = os.path.join(root, vit_name, name)
        idx_path  = os.path.join(feat_dir, "max_activating_image_indices.pt")
        acts_path = os.path.join(feat_dir, "sae_mean_acts.pt")

        if os.path.exists(idx_path):
            max_act_imgs[name] = torch.load(idx_path, map_location="cpu")
        else:
            max_act_imgs[name] = None

        if os.path.exists(acts_path):
            mean_acts[name] = torch.load(acts_path, map_location="cpu")
        else:
            mean_acts[name] = None

    return max_act_imgs, mean_acts
